#!/usr/bin/env bash
set -euo pipefail
: "${FRONTEND_BUCKET:?Set FRONTEND_BUCKET}"
: "${CLOUDFRONT_DISTRIBUTION_ID:?Set CLOUDFRONT_DISTRIBUTION_ID}"
: "${VITE_API_BASE_URL:?Set VITE_API_BASE_URL}"
: "${VITE_COGNITO_REGION:?Set VITE_COGNITO_REGION}"
: "${VITE_COGNITO_USER_POOL_ID:?Set VITE_COGNITO_USER_POOL_ID}"
: "${VITE_COGNITO_CLIENT_ID:?Set VITE_COGNITO_CLIENT_ID}"

cd frontend
npm ci
VITE_API_BASE_URL="$VITE_API_BASE_URL" \
VITE_AUTH_MODE=local \
VITE_COGNITO_REGION="$VITE_COGNITO_REGION" \
VITE_COGNITO_USER_POOL_ID="$VITE_COGNITO_USER_POOL_ID" \
VITE_COGNITO_CLIENT_ID="$VITE_COGNITO_CLIENT_ID" \
npm run build

aws s3 sync dist/ "s3://$FRONTEND_BUCKET/" --delete
aws cloudfront create-invalidation --distribution-id "$CLOUDFRONT_DISTRIBUTION_ID" --paths "/*"
